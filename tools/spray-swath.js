// Builds the SPRAY_SWATH table in src/js/70-planner.js: the effective swath (m) of one pass for every nozzle
// mount, droplet class, spray height, and speed, measured with sprayPassSwath from src/js/00-sim.js.
// Run with: node tools/spray-swath.js   (takes a few minutes). It rewrites the table in place.
// A test re-measures two entries and fails when the table no longer matches the sim.
var fs = require('fs'), path = require('path'), vm = require('vm');
var root = path.join(__dirname, '..'), S = {};
vm.createContext(S); vm.runInContext(fs.readFileSync(path.join(root, 'src/js/00-sim.js'), 'utf8'), S);
var heights = [2, 3, 4, 5], speeds = [2, 4, 6], out = {};
Object.keys(S.PARAMS.spray.nozzles).forEach(function(mount){
  out[mount] = {};
  Object.keys(S.PARAMS.spray.classes).forEach(function(cls){
    out[mount][cls] = heights.map(function(alt){
      return speeds.map(function(speed){ var w = S.sprayPassSwath({ cls: cls, mount: mount, alt: alt, speed: speed }).swath; process.stdout.write('.'); return +w.toFixed(1); });
    });
  });
});
var lines = ['var SPRAY_SWATH = { // generated by tools/spray-swath.js from sprayPassSwath. Do not edit by hand',
  '  heights: ' + JSON.stringify(heights) + ', speeds: ' + JSON.stringify(speeds) + ', // rows by height (m), columns by speed (m/s)'];
Object.keys(out).forEach(function(mount, mi, ms){
  lines.push('  ' + mount + ': {');
  Object.keys(out[mount]).forEach(function(cls, ci, cs){ lines.push('    ' + JSON.stringify(cls) + ': ' + JSON.stringify(out[mount][cls]) + (ci < cs.length - 1 ? ',' : '')); });
  lines.push('  }' + (mi < ms.length - 1 ? ',' : ''));
});
lines.push('};');
var file = path.join(root, 'src/js/70-planner.js'), text = fs.readFileSync(file, 'utf8'), a = text.indexOf('var SPRAY_SWATH = {'), b = text.indexOf('\n};', a);
if (a < 0 || b < 0) throw new Error('SPRAY_SWATH block not found in 70-planner.js');
fs.writeFileSync(file, text.slice(0, a) + lines.join('\n') + text.slice(b + 3));
console.log('\nwrote SPRAY_SWATH to src/js/70-planner.js');
